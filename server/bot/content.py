def prices_text() -> str:
    lines = ["💳 <b>Стоимость и пакеты участия</b>\n"]
    for key in PACKAGE_ORDER:
        p = PACKAGES[key]
        lines.append(f"• <b>{p['title']}</b> — {p['price']}\n  {p['desc']}")
    lines.append("\nВыберите «Оплатить участие», чтобы перейти к оплате пакета.")
    return "\n".join(lines)


